# Creating a tuple
my_tuple = (23, 67, 45, 34, 23, "Kirthana", "Koushik", "Padmavathi", "Uday", "Priya", "Vignesh")

print("Original Tuple:")
print(my_tuple)

# 1. count() – Counts how many times an element appears
print("\nCount of 23:", my_tuple.count(23))

# 2. index() – Finds the index position of an element
print("Index of 'Kirthana':", my_tuple.index("Kirthana"))
